// Node booking model tests; fixture contacts are fictional and never printed.
/* eslint-disable @typescript-eslint/no-require-imports -- Reuse the installed TSX loader without adding dependencies. */
require('./public-pages.cjs');
const assert = require('node:assert/strict');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const { BOOKING_SETTINGS } = require('../src/config/booking.ts');
const { BOOKING_COPY } = require('../src/config/booking-copy.ts');
const { PRACTICE } = require('../src/config/practice.ts');
const { makeMockSchedule, availableMockSlots } = require('../src/features/booking/schedule.ts');
const { initialBookingState, bookingReducer, emptyDetails } = require('../src/features/booking/state.ts');
const { validateDetails, validateSelection } = require('../src/features/booking/validation.ts');
const { formatTime, practiceDate } = require('../src/features/booking/time.ts');
const schedule = makeMockSchedule('2026-10-13T16:00:00.000Z', BOOKING_SETTINGS, BOOKING_SETTINGS.locationIds);
const input = { name:'Demo Visitor',phone:'2025550101',email:'demo@example.test',dateOfBirth:'2000-01-15',reason:'Fictional visit only',smsConsent:false,emailConsent:false };
assert.deepEqual(validateDetails(input,BOOKING_SETTINGS,schedule.referenceUtc),{});
for (const value of [null, [], {}, { ...input, smsConsent:'true' }]) assert.ok(Object.keys(validateDetails(value,BOOKING_SETTINGS,schedule.referenceUtc)).length);
for (const dateOfBirth of ['2026-10-14','2025-02-29','2000-02-30','bad']) assert.equal(validateDetails({...input,dateOfBirth},BOOKING_SETTINGS,schedule.referenceUtc).dateOfBirth,'birthInvalid');
assert.equal(validateDetails({...input,dateOfBirth:'2000-02-29'},BOOKING_SETTINGS,schedule.referenceUtc).dateOfBirth,undefined);
assert.equal(validateDetails({...input,email:'bad'},BOOKING_SETTINGS,schedule.referenceUtc).email,'emailInvalid');
assert.equal(validateDetails({...input,email:'demo\u0000@example.test'},BOOKING_SETTINGS,schedule.referenceUtc).email,'emailInvalid');
assert.equal(validateDetails({...input,phone:'123'},BOOKING_SETTINGS,schedule.referenceUtc).phone,'phoneInvalid');
assert.equal(validateDetails({...input,reason:'x'.repeat(BOOKING_SETTINGS.reasonLimit+1)},BOOKING_SETTINGS,schedule.referenceUtc).reason,'reasonRequired');
let state=initialBookingState(BOOKING_SETTINGS);
assert.equal(state.details.smsConsent,false);
assert.equal(validateSelection(state.selection,BOOKING_SETTINGS,schedule,0).selection,'typeRequired');
state=bookingReducer(state,{type:'appointmentType',id:'new-patient',firstAvailableId:BOOKING_SETTINGS.firstAvailableId});
const firstDay=schedule.days.find(day => day.id >= '2026-10-15' && day.scenario === 'ready').id;
state=bookingReducer(state,{type:'date',id:firstDay});
const slots=availableMockSlots(schedule,BOOKING_SETTINGS,state.selection);
assert.equal(slots.length,16); // Half-hour starts from 9:00 AM through 4:30 PM for a 30-minute visit.
assert.equal(new Set(slots.map(slot=>slot.startUtc)).size,slots.length);
state=bookingReducer(state,{type:'slot',id:slots[0].id});
assert.deepEqual(validateSelection(state.selection,BOOKING_SETTINGS,schedule,3),{});
assert.equal(validateSelection({...state.selection,slotId:'forged'},BOOKING_SETTINGS,schedule,3).selection,'slotRequired');
const unavailable=schedule.days.find(day=>day.scenario==='unavailable');
assert.equal(availableMockSlots(schedule,BOOKING_SETTINGS,{...state.selection,dateId:unavailable.id}).length,0);
assert.equal(availableMockSlots(schedule,{...BOOKING_SETTINGS,types:BOOKING_SETTINGS.types.map(type=>({...type,leadHours:10000}))},state.selection).length,0);
const urgent=availableMockSlots(schedule,BOOKING_SETTINGS,{...state.selection,typeId:'urgent'});
assert.ok(urgent.every(slot=>BOOKING_SETTINGS.types.find(type=>type.id==='urgent').providerIds.includes(slot.providerId)));
const changed=bookingReducer(state,{type:'provider',id:BOOKING_SETTINGS.providers[1].id});
assert.equal(changed.selection.dateId,'');assert.equal(changed.selection.slotId,'');
const customSettings={...BOOKING_SETTINGS,firstAvailableId:'any-doctor'};
const custom=bookingReducer(state,{type:'appointmentType',id:'urgent',firstAvailableId:customSettings.firstAvailableId});
assert.equal(custom.selection.providerId,'any-doctor');
state=bookingReducer(state,{type:'details',details:input});
state=bookingReducer(state,{type:'step',step:3});
state=bookingReducer(state,{type:'review'});
assert.equal(state.step,3); // Review actions do not add a fifth step.
const BookingSummary=require('../src/features/booking/BookingSummary.tsx').default;
const review=renderToStaticMarkup(React.createElement(BookingSummary,{state,settings:BOOKING_SETTINGS,schedule,locations:PRACTICE.locations,copy:BOOKING_COPY,contact:true}));
assert.match(review,/Demo Visitor/);
state=bookingReducer(state,{type:'complete'});
assert.deepEqual(state.details,emptyDetails());
const result=renderToStaticMarkup(React.createElement(BookingSummary,{state,settings:BOOKING_SETTINGS,schedule,locations:PRACTICE.locations,copy:BOOKING_COPY}));
assert.doesNotMatch(result,/Demo Visitor|demo@example.test|Fictional visit/);
assert.deepEqual(schedule,makeMockSchedule('2026-10-13T16:00:00.000Z',BOOKING_SETTINGS,BOOKING_SETTINGS.locationIds));
assert.equal(practiceDate('2026-10-13T01:00:00Z','America/New_York'),'2026-10-12');
assert.match(formatTime('2026-03-08T07:00:00Z','America/New_York','en-US'),/3:00.*AM.*EDT/);
assert.match(formatTime('2026-11-01T05:30:00Z','America/New_York','en-US'),/1:30.*AM.*EDT/);
assert.match(formatTime('2026-11-01T06:30:00Z','America/New_York','en-US'),/1:30.*AM.*EST/);
const BookingForm=require('../src/features/booking/BookingForm.tsx').default;
const html=renderToStaticMarkup(React.createElement(BookingForm,{settings:BOOKING_SETTINGS,schedule,locations:PRACTICE.locations,copy:BOOKING_COPY}));
assert.match(html,/<fieldset disabled=""/);
assert.equal((html.match(/booking-progress-number/g)||[]).length,4);
assert.doesNotMatch(html,/<form[^>]*(action|method)=/);
console.log('Passed: minimum fields, optional consent, dates/DST, eligibility/lead times, dependent resets, demo-only completion and disabled server form.');
